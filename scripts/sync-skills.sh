#!/usr/bin/env bash
# Copies the agent instructions and the CLAUDE.md template into each skill's
# references/ folder, so every skill is self-contained when installed alone
# (Agent Skills harnesses such as Codex, Cursor, Gemini CLI or Copilot have no
# access to agents/ or templates/). The agents/ and templates/ files are the
# source of truth. Usage: scripts/sync-skills.sh [--check]
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
check="${1:-}"
stale=0

# body <file>: the file without its YAML frontmatter
body() { awk 'NR==1 && $0=="---" {fm=1; next} fm && $0=="---" {fm=0; next} !fm' "$1"; }

# put <target> <generator...>: write or check one reference file
put() {
  local target="$root/$1"; shift
  local content
  content="$(printf '<!-- Generated by scripts/sync-skills.sh. Edit the source file instead. -->\n'; "$@")"
  if [[ "$check" == "--check" ]]; then
    if [[ ! -f "$target" ]] || [[ "$(cat "$target")" != "$content" ]]; then
      echo "stale: ${target#"$root"/}"; stale=1
    fi
  else
    mkdir -p "$(dirname "$target")"
    printf '%s\n' "$content" > "$target"
  fi
}

put skills/octane-audit/references/auditor.md      body "$root/agents/octane-auditor.md"
put skills/octane-audit/references/pest-writer.md  body "$root/agents/pest-writer.md"
put skills/migrate-lumen/references/auditor.md     body "$root/agents/octane-auditor.md"
put skills/migrate-lumen/references/pest-writer.md body "$root/agents/pest-writer.md"
put skills/laravel-claude-md/references/CLAUDE.md  cat  "$root/templates/CLAUDE.md"

if [[ "$check" == "--check" && "$stale" == 1 ]]; then
  echo "Run scripts/sync-skills.sh and commit the result." >&2
  exit 1
fi
